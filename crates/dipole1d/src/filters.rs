//! Hankel transform digital filters
//!
//! Implements the Kong (2007) digital filters for fast Hankel transforms

/// Available Hankel filter types
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum HankelFilter {
    /// Kong 61-point filter
    Kong61,
    /// Kong 201-point filter (default, good balance)
    #[default]
    Kong201,
    /// Kong 241-point filter (highest accuracy)
    Kong241,
}

impl HankelFilter {
    /// Get the filter coefficients
    pub fn coefficients(&self) -> &'static FilterCoefficients {
        match self {
            HankelFilter::Kong61 => &KONG_61,
            HankelFilter::Kong201 => &KONG_201,
            HankelFilter::Kong241 => &KONG_241,
        }
    }

    /// Get number of filter points
    pub fn n_points(&self) -> usize {
        self.coefficients().base.len()
    }
}

/// Filter coefficients for Hankel transform
pub struct FilterCoefficients {
    /// Base (lambda) values
    pub base: &'static [f64],
    /// J0 Bessel function coefficients
    pub j0: &'static [f64],
    /// J1 Bessel function coefficients
    pub j1: &'static [f64],
}

